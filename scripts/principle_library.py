#!/usr/bin/env python3
"""Build and retrieve a portable, evidence-linked working-principle library.

Markdown documents are the authored source. The index and task packets are views.
This module does not infer principles, change personal evidence, or schedule jobs.
Uses Python's standard library and the existing workspace lock.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from datetime import date
from pathlib import Path

from memoryctl import atomic_write_text, workspace_lock

ROOT = Path(__file__).resolve().parents[1]
LEDGER = "state/decision_memory_v1.json"
MARKER = "<!-- Generated by principle_library.py; edit principle documents, then run sync. -->"
CATEGORIES = {
    "research_and_evidence": "Research and evidence",
    "writing_and_sources": "Writing and sources",
    "tools_and_collaboration": "Tools and collaboration",
    "learning_and_memory": "Learning and memory",
}
SECTIONS = ["Core principle", "Reasoning", "Application", "Limits and pitfalls",
            "Related principles", "Sources and standing"]
ID = re.compile(r"[A-Z][0-9]{2,}")


def fingerprint(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def state_at(workspace):
    path = workspace / LEDGER
    return json.loads(path.read_text()) if path.exists() else {"events": [], "principles": []}


def safe_path(workspace, relative):
    path = workspace / relative
    if not path.resolve().is_relative_to(workspace.resolve()):
        raise ValueError(f"Path escapes workspace: {relative}")
    return path


def parse(path):
    text = path.read_text()
    if not text.startswith("---\n"):
        return None  # historical landing pages and README files are not entries
    parts = text.split("\n---\n", 1)
    if len(parts) != 2:
        raise ValueError(f"Unclosed metadata: {path.name}")
    meta = {}
    for line in parts[0].splitlines()[1:]:
        key, separator, value = line.partition(":")
        if not separator or key in meta:
            raise ValueError(f"Invalid/duplicate metadata in {path.name}: {key}")
        value = value.strip()
        # Deliberately restricted YAML subset: plain text or JSON strings/lists.
        meta[key] = json.loads(value) if value.startswith(("[", '"')) else value
    body = parts[1]
    title = re.search(r"^# (.+)$", body, re.M)
    if not ID.fullmatch(meta.get("id", "")):
        raise ValueError(f"{path.name}: id must be stable, such as X01")
    for key in ("category", "summary", "updated"):
        if not isinstance(meta.get(key), str) or not meta[key].strip():
            raise ValueError(f"{path.name}: missing {key}")
    if meta["category"] not in CATEGORIES:
        raise ValueError(f"{path.name}: unknown category")
    date.fromisoformat(meta["updated"])
    if meta.get("status", "active") not in {"active", "retired"}:
        raise ValueError(f"{path.name}: status must be active or retired")
    for key in ("aliases", "ledger_ids", "event_ids"):
        value = meta.setdefault(key, [])
        if not isinstance(value, list) or not all(isinstance(x, str) and x for x in value):
            raise ValueError(f"{path.name}: {key} must be a JSON list of strings")
        if len(set(value)) != len(value):
            raise ValueError(f"{path.name}: duplicate {key}")
    if not title:
        raise ValueError(f"{path.name}: missing title")
    for number, section in enumerate(SECTIONS, 1):
        pattern = rf"^## {number}\. {re.escape(section)}\n(.+?)(?=^## |\Z)"
        match = re.search(pattern, body, re.M | re.S)
        if not match or not match.group(1).strip():
            raise ValueError(f"{path.name}: missing section {section}")
    return {"path": path, "meta": meta, "body": body, "title": title.group(1), "text": text}


def evidence_snapshot(entry, state):
    meta = entry["meta"]
    principles = {p["id"]: p for p in state["principles"]}
    events = {e["id"]: e for e in state["events"]}
    linked = []
    event_ids = set(meta["event_ids"])
    for key in meta["ledger_ids"]:
        if key not in principles:
            raise ValueError(f"{meta['id']}: unknown ledger ID {key}")
        p = principles[key]
        linked.append(p)
        event_ids.update(p.get("support_event_ids", []))
        event_ids.update(p.get("counter_event_ids", []))
    # Include later corrections, including corrections to corrections.
    while True:
        successors = {e["id"] for e in events.values()
                      if event_ids.intersection(e.get("supersedes_event_ids", []))}
        if successors <= event_ids:
            break
        event_ids.update(successors)
    missing = event_ids - events.keys()
    if missing:
        raise ValueError(f"{meta['id']}: unknown event IDs {sorted(missing)}")
    if not linked and not event_ids:
        sources = entry["body"].split("## 6. Sources and standing", 1)[1]
        if not re.search(r"\]\(https?://[^)]+\)", sources):
            raise ValueError(f"{meta['id']}: needs ledger evidence or an external source link")
    return {"principles": sorted(linked, key=lambda p: p["id"]),
            "events": [events[key] for key in sorted(event_ids)]}


def entries_at(workspace, state=None):
    state = state if state is not None else state_at(workspace)
    entries, names = [], set()
    for path in sorted((workspace / "principles").glob("*.md")):
        safe_path(workspace, path.relative_to(workspace))
        entry = parse(path)
        if entry is None:
            continue
        meta = entry["meta"]
        for key in [meta["id"], *meta["aliases"]]:
            if key in names:
                raise ValueError(f"Duplicate principle ID or alias: {key}")
            names.add(key)
        snapshot = evidence_snapshot(entry, state)
        entry["evidence"] = snapshot
        entry["digest"] = fingerprint(snapshot)
        linked = bool(snapshot["principles"] or snapshot["events"])
        entry["needs_review"] = linked and meta.get("evidence_digest") != entry["digest"]
        entry["retired"] = meta.get("status") == "retired" or any(
            p["status"] == "retired" for p in snapshot["principles"])
        # Health is shown at retrieval time. It does not rewrite evidence or
        # make all documents stale when a check timestamp advances.
        entry["source_health"] = {key: state.get("principle_source_health", {}).get(key, {})
                                  for key in meta["ledger_ids"]}
        entries.append(entry)
    return sorted(entries, key=lambda e: e["meta"]["id"])


def index_text(entries):
    lines = ["# Principles", "", MARKER, "",
             "Read this index first. Select only entries relevant to the current decision,",
             "usually one to three. Current instructions and evidence take precedence.",
             "Use the task-context command before applying a selected entry. It checks",
             "current evidence and includes the full reasoning, limits, and sources.", ""]
    for category, title in CATEGORIES.items():
        group = [e for e in entries if e["meta"]["category"] == category and not e["retired"]]
        if not group:
            continue
        lines += [f"## {title}", "", "| ID | Principle | What it means |", "| --- | --- | --- |"]
        for e in group:
            clean = lambda value: value.replace("|", "\\|")
            flag = " **Needs evidence review.**" if e["needs_review"] else ""
            lines.append(f"| {e['meta']['id']} | [{clean(e['title'])}]({e['path'].name}) | "
                         f"{clean(e['meta']['summary'])}{flag} |")
        lines.append("")
    if not entries:
        lines += ["No principles yet. Add a sourced document using the installed template.", ""]
    retired = [e for e in entries if e["retired"]]
    if retired:
        lines += ["## Retained history", ""]
        lines += [f"- {e['meta']['id']}: [{e['title']}]({e['path'].name}) (retired)" for e in retired]
        lines.append("")
    lines += ["Stable IDs survive title or category changes. Keep earlier IDs as aliases when merging.",
              "Retired entries stay available as history. L2 use does not require L3 promotion.",
              "Record consequential use or correction in existing project notes.", ""]
    return "\n".join(lines)


def sync(workspace, reviewed=(), state=None, check=False, review_packet=None):
    """Validate and build views; mutation callers must hold workspace_lock."""
    entries = entries_at(workspace, state)
    by_id = {e["meta"]["id"]: e for e in entries}
    unknown = set(reviewed) - by_id.keys()
    if unknown:
        raise ValueError(f"Unknown reviewed IDs: {sorted(unknown)}")
    if check and (reviewed or review_packet is not None):
        raise ValueError("--check cannot acknowledge an evidence review")
    if reviewed:
        if state is not None:
            raise ValueError("Evidence review must check the current ledger")
        if not isinstance(review_packet, dict) or not isinstance(review_packet.get("principles"), list):
            raise ValueError("--reviewed requires a saved --review-packet from review")
        expected = {}
        for item in review_packet["principles"]:
            if (not isinstance(item, dict) or not isinstance(item.get("id"), str)
                    or item["id"] in expected or not isinstance(item.get("evidence_digest"), str)):
                raise ValueError("Invalid principle evidence in review packet; run review again")
            expected[item["id"]] = item["evidence_digest"]
        changed = [key for key in reviewed if expected.get(key) != by_id[key]["digest"]]
        if changed:
            raise ValueError(f"Stale or missing reviewed evidence for {sorted(changed)}; "
                             "run review again and inspect the changed evidence")
    elif review_packet is not None:
        raise ValueError("--review-packet requires --reviewed")
    # Validate every selected snapshot before writing any document.
    for key in reviewed:
        e = by_id[key]
        meta = e["meta"]
        meta["evidence_digest"] = e["digest"]
        header = "\n".join(f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in meta.items())
        atomic_write_text(e["path"], f"---\n{header}\n---\n{e['body']}")
        e["needs_review"] = False
    target = safe_path(workspace, "principles/INDEX.md")
    expected = index_text(entries)
    if check:
        if not target.exists() or target.read_text() != expected:
            raise ValueError("Principle index is stale; run sync")
    elif not target.exists() or target.read_text() != expected:
        atomic_write_text(target, expected)
    return {"principles": len(entries),
            "needs_review": [e["meta"]["id"] for e in entries if e["needs_review"] and not e["retired"]]}


def sync_if_managed(workspace, state):
    index = workspace / "principles/INDEX.md"
    if index.is_file() and MARKER in index.read_text():
        return sync(workspace, state=state)
    return None


def review_packet(workspace):
    state = state_at(workspace)
    entries = entries_at(workspace, state)
    links = {}
    for entry in entries:
        for event in entry["evidence"]["events"]:
            links.setdefault(event["id"], []).append(entry["meta"]["id"])
    return {
        "state_digest": fingerprint(state),
        "instruction": "Review choices and corrections in context. Unlinked events are not a backlog or a principle quota.",
        "principles": [{"id": e["meta"]["id"], "path": str(e["path"]),
                        "needs_review": e["needs_review"], "retired": e["retired"],
                        "evidence_digest": e["digest"],
                        "source_health": e["source_health"]} for e in entries],
        "events": [{"id": e["id"], "choice": e["choice"], "attribution": e["attribution"],
                    "linked_principles": links.get(e["id"], []),
                    "supersedes_event_ids": e.get("supersedes_event_ids", [])}
                   for e in state["events"]],
    }


def task_context(workspace, ids):
    if not 1 <= len(ids) <= 3:
        raise ValueError("Select one to three principles from the index")
    entries = entries_at(workspace)
    lookup = {key: e for e in entries for key in [e["meta"]["id"], *e["meta"]["aliases"]]}
    if any(key not in lookup for key in ids):
        raise ValueError("Unknown principle ID or alias")
    selected = [lookup[key] for key in ids]
    if len({e["meta"]["id"] for e in selected}) != len(selected):
        raise ValueError("Select each principle only once")
    for e in selected:
        if e["retired"] or e["needs_review"]:
            raise ValueError(f"{e['meta']['id']}: retired or changed evidence; review before task use")
    lines = ["# Selected working principles", "",
             "These are scoped defaults, subordinate to the current request and evidence.",
             "The check covers linked evidence identity, not the semantic correctness of authored prose.",
             "Missing source context is not newly verified by retrieval. No use quota applies.", ""]
    for e in selected:
        lines += [f"## {e['meta']['id']} — {e['title']}", "", f"Source document: {e['path']}", ""]
        for key, health in e["source_health"].items():
            lines += [f"Evidence health for {key}: {health.get('status', 'unchecked')}; "
                      f"last verified {health.get('last_verified_at') or 'not recorded'}.", ""]
        lines += [e["body"].strip(), ""]
    lines += ["If use changes a consequential decision, record the ID, action, reason, and",
              "outcome or correction in the owning project note. L1 collects that registered",
              "note on a later run. Agent compliance is not evidence of a personal belief.", ""]
    return "\n".join(lines)


def setup(workspace, registry=None, python=None):
    workspace = workspace.resolve()
    config = safe_path(workspace, "config/repos.json")
    if not config.exists() and registry is None:
        raise ValueError("New workspace needs --registry <repos.json>; no machine paths are assumed")
    if config.exists() and registry is not None:
        if json.loads(config.read_text()) != json.loads(registry.read_text()):
            raise ValueError("Registry already exists; reconcile it explicitly")
    registry_text = config.read_text() if config.exists() else registry.read_text()
    registered = json.loads(registry_text)
    if registered.get("schema_version") != 1 or not isinstance(registered.get("repos"), list):
        raise ValueError("Registry needs schema_version 1 and a repos list")
    names = set()
    for repo in registered["repos"]:
        if not isinstance(repo, dict) or not repo.get("name") or repo["name"] in names:
            raise ValueError("Registry needs unique named repositories")
        if not isinstance(repo.get("root"), str) or not Path(repo["root"]).is_absolute():
            raise ValueError("Registry repository roots must be absolute")
        if not isinstance(repo.get("maintenance_enabled", True), bool):
            raise ValueError("maintenance_enabled must be boolean")
        names.add(repo["name"])
    # Setup validates existing content before creating or replacing generated files.
    entries_at(workspace)
    values = {"WORKSPACE": str(workspace), "SKILL_ROOT": str(ROOT),
              "PYTHON": str(Path(python or sys.executable).expanduser().absolute())}
    outputs = {}
    for name in ("daily-observer.txt", "weekly-review.txt", "task-instructions.md"):
        content = (ROOT / "templates/personal-memory" / name).read_text()
        for key, value in values.items():
            content = content.replace("{{" + key + "}}", value)
        outputs[safe_path(workspace, "config/prompts/" + name)] = content
    for repo in registered["repos"]:
        if not repo.get("maintenance_enabled", True):
            continue
        name = repo["name"]
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*", name):
            raise ValueError("Maintenance prompt names need a safe repository short name")
        content = (ROOT / "templates/personal-memory/repo-maintenance.txt").read_text()
        for key, value in {**values, "REPO_NAME": name, "REPO_ROOT": repo["root"]}.items():
            content = content.replace("{{" + key + "}}", value)
        outputs[safe_path(workspace, f"config/prompts/maintenance-{name}.txt")] = content
    guide = safe_path(workspace, "AGENTS.md")
    start, end = "<!-- project-memory:begin -->", "<!-- project-memory:end -->"
    block = (f"{start}\n## Reproducible personal memory\n\n"
             f"Use the installed skill at `{ROOT}/SKILL.md`.\n"
             "Follow its `references/personal_memory_workflows.md` for daily collection,\n"
             "weekly review, task retrieval, and feedback. Local entry prompts are\n"
             "generated in `config/prompts/`; rerun skill setup after moving paths.\n"
             "`principles/*.md` are authored sources; `principles/INDEX.md` is generated.\n"
             f"{end}")
    existing = guide.read_text() if guide.exists() else "# Personal memory workspace\n"
    if (start in existing) != (end in existing):
        raise ValueError("Incomplete project-memory block in workspace AGENTS.md")
    if start in existing:
        updated = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda m: block,
                         existing, flags=re.S)
    else:
        updated = existing.rstrip() + "\n\n" + block + "\n"
    outputs[guide] = updated
    if not config.exists():
        outputs[config] = registry_text
    with workspace_lock(workspace):
        for path, content in outputs.items():
            if not path.exists() or path.read_text() != content:
                atomic_write_text(path, content)
        sync(workspace)
    return {"workspace": str(workspace), "prompts": "config/prompts",
            "scheduler_changed": False, "repository_instructions_changed": False}


def bind(workspace, instructions):
    """Install an explicit task route in a caller-selected instruction file."""
    source = workspace / "config/prompts/task-instructions.md"
    if not source.is_file():
        raise ValueError("Run setup before binding task instructions")
    text = source.read_text()
    text = re.sub(r"\A<!--.*?-->\s*", "", text, count=1, flags=re.S)
    start, end = "<!-- project-memory-task:begin -->", "<!-- project-memory-task:end -->"
    block = f"{start}\n{text.strip()}\n{end}"
    existing = instructions.read_text() if instructions.exists() else ""
    if (start in existing) != (end in existing):
        raise ValueError("Incomplete project-memory task block")
    if start in existing:
        updated = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda m: block,
                         existing, flags=re.S)
    else:
        updated = existing + ("\n\n" if existing and not existing.endswith("\n\n") else "") + block + "\n"
    if updated != existing:
        atomic_write_text(instructions, updated)
    return {"instructions": str(instructions), "changed": updated != existing}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    p = commands.add_parser("setup")
    p.add_argument("--workspace", type=Path, required=True)
    p.add_argument("--registry", type=Path)
    p.add_argument("--python")
    p = commands.add_parser("bind")
    p.add_argument("--workspace", type=Path, required=True)
    p.add_argument("--instructions", type=Path, required=True)
    p = commands.add_parser("sync")
    p.add_argument("--workspace", type=Path, required=True)
    p.add_argument("--check", action="store_true")
    p.add_argument("--reviewed", nargs="+", default=[])
    p.add_argument("--review-packet", type=Path, help="Saved output of review for the evidence inspected")
    p = commands.add_parser("review")
    p.add_argument("--workspace", type=Path, required=True)
    p = commands.add_parser("task-context")
    p.add_argument("--workspace", type=Path, required=True)
    p.add_argument("--ids", nargs="+", required=True)
    args = parser.parse_args()
    w = args.workspace.resolve()
    try:
        if args.command == "setup":
            result = setup(w, args.registry, args.python)
        elif args.command == "bind":
            result = bind(w, args.instructions.expanduser().resolve())
        elif args.command == "sync":
            packet = json.loads(args.review_packet.read_text()) if args.review_packet else None
            if args.check:
                result = sync(w, reviewed=args.reviewed, check=True, review_packet=packet)
            else:
                with workspace_lock(w):
                    result = sync(w, reviewed=args.reviewed, review_packet=packet)
        elif args.command == "review":
            result = review_packet(w)
        else:
            print(task_context(w, args.ids))
            return
        print(json.dumps(result, indent=2, ensure_ascii=False))
    except (ValueError, OSError, RuntimeError) as exc:
        parser.exit(1, f"Error: {exc}\n")


if __name__ == "__main__":
    main()
